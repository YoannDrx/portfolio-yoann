export const getDevWorkExperiences = (locale: Locale = "fr") =>
  getWorkExperiences(locale).filter((exp) => {
    const role = exp.role.toLowerCase();
    return (
      role.includes("développeur") ||
      role.includes("developer") ||
      role.includes("dev")
    );
  });

export const getTotalYearsOfExperience = (): number => {
  const devStart = new Date("2023-02-01");
  const now = new Date();
  const years =
    (now.getTime() - devStart.getTime()) / (1000 * 60 * 60 * 24 * 365);
  return Math.floor(years);
};
