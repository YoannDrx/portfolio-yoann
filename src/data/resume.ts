export const getTotalYearsOfExperience = (): number => {
  const devStart = new Date("2023-02-01");
  const now = new Date();
  const years =
    (now.getTime() - devStart.getTime()) / (1000 * 60 * 60 * 24 * 365);
  return Math.floor(years);
};
